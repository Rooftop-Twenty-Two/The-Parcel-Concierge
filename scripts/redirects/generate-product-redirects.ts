#!/usr/bin/env node
/**
 * Generates the per-product redirect rows from a retain/remove list.
 *
 * There are roughly 2,300 SKUs on the old site and around 250 to 400 will
 * survive. Hand-writing that many rows is how a redirect map ends up with
 * typos, duplicates and gaps, so this generates them and the output is
 * pasted into data/redirects/redirects.csv for review.
 *
 * Input: a CSV with these columns.
 *
 *   handle,decision,kind,parent
 *
 *   handle    the old Shopify product handle
 *   decision  retain | remove
 *   kind      hamper | wine | spirit | addon   (retained products only)
 *   parent    the listing path a removed product should land on. Required
 *             for removals: a removed product NEVER redirects to the
 *             homepage, it goes to its parent listing so the shopper lands
 *             somewhere that sells something close to what they wanted.
 *
 * Usage:
 *   node --experimental-strip-types scripts/redirects/generate-product-redirects.ts \
 *     --input data/catalogue/retain-remove.csv > /tmp/product-redirects.csv
 */

import { readFileSync } from 'node:fs'
import { productPathFor } from '../../src/lib/routes.ts'
import type { ProductKind } from '../../src/lib/commerce/types.ts'

type Row = { handle: string; decision: string; kind: string; parent: string; line: number }

function parseArgs(argv: string[]): { input: string } {
  let input = ''
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--input' || argv[i] === '-i') input = argv[++i] ?? ''
  }
  if (!input) {
    console.error('Usage: generate-product-redirects.ts --input <retain-remove.csv>')
    process.exit(1)
  }
  return { input }
}

function main(): void {
  const { input } = parseArgs(process.argv.slice(2))
  const text = readFileSync(input, 'utf8')

  const rows: Row[] = []
  const problems: string[] = []

  text.split(/\r?\n/).forEach((raw, index) => {
    const line = index + 1
    const trimmed = raw.trim()
    if (!trimmed || trimmed.startsWith('#')) return
    if (line === 1 && trimmed.startsWith('handle,')) return

    const [handle = '', decision = '', kind = '', parent = ''] = trimmed.split(',').map((c) => c.trim())
    if (!handle) return
    rows.push({ handle, decision, kind, parent, line })
  })

  const out: string[] = []
  const seen = new Set<string>()

  for (const row of rows) {
    const source = `/products/${row.handle}`

    if (seen.has(source)) {
      problems.push(`line ${row.line}: duplicate handle "${row.handle}".`)
      continue
    }
    seen.add(source)

    if (row.decision === 'retain') {
      if (!isKind(row.kind)) {
        problems.push(`line ${row.line}: "${row.handle}" is retained but kind "${row.kind}" is not a product kind.`)
        continue
      }
      out.push(`${source},${productPathFor(row.kind, row.handle)},301,Retained ${row.kind}`)
      continue
    }

    if (row.decision === 'remove') {
      if (!row.parent.startsWith('/')) {
        // A removed product with no parent would have to go to the
        // homepage, and the brief is explicit that it must not.
        problems.push(
          `line ${row.line}: "${row.handle}" is removed but has no parent listing. A removed product never redirects to the homepage.`,
        )
        continue
      }
      out.push(`${source},${row.parent},301,Removed, sent to its parent listing`)
      continue
    }

    problems.push(`line ${row.line}: decision must be "retain" or "remove", found "${row.decision}".`)
  }

  if (problems.length) {
    console.error(`${problems.length} problem${problems.length === 1 ? '' : 's'}:`)
    for (const problem of problems) console.error(`  ! ${problem}`)
    console.error()
    console.error('Nothing generated. Fix the retain/remove list first.')
    process.exit(1)
  }

  console.log('# Generated by scripts/redirects/generate-product-redirects.ts. Do not hand edit.')
  console.log(`# ${out.length} product rules from ${input}`)
  for (const line of out) console.log(line)
}

function isKind(value: string): value is ProductKind {
  return value === 'hamper' || value === 'wine' || value === 'spirit' || value === 'addon'
}

main()
